const DIMENSIONS: Dimension[] = ['D1', 'D2', 'D3', 'D4', 'D5', 'D6'];

function emptyScores(): DimensionScores {
  return { D1: 0, D2: 0, D3: 0, D4: 0, D5: 0, D6: 0 };
}

/** Q1~Q23, Q25 점수 합산 + Q24 주민별 가중치 누적 → 최종 주민 결정 */
export function calculateResident(answers: Answer[]): ResidentKey {
  const dimScores = emptyScores();
  const residentWeights: Record<ResidentKey, number> = {
    guardian: 0,
    guide: 0,
    pioneer: 0,
    lightkeeper: 0,
    voyager: 0,
    wayfarer: 0,
    forestKeeper: 0,
    sculptor: 0,
  };

  for (const answer of answers) {
    // 1) 차원 점수 합산
    for (const dim of DIMENSIONS) {
      const val = answer.scores[dim];
      if (val !== undefined) {
        dimScores[dim] = (dimScores[dim] || 0) + val;
      }
    }
    // 2) Q24 주민 가중치 누적
    if (answer.residentWeights) {
      for (const key of answer.residentWeights as ResidentKey[]) {
        residentWeights[key] += 1;
      }
    }
  }

  // 각 주민별 매칭 점수 계산
  const residentScores: Record<ResidentKey, number> = {
    guardian: 0,
    guide: 0,
    pioneer: 0,
    lightkeeper: 0,
    voyager: 0,
    wayfarer: 0,
    forestKeeper: 0,
    sculptor: 0,
  };

  const allKeys = Object.keys(RESIDENTS) as ResidentKey[];

  for (const key of allKeys) {
    const r = RESIDENTS[key];
    let score = 0;

    // 주요 차원 ×2
    for (const { dim, sign } of r.primary) {
      score += sign * (dimScores[dim] || 0) * 2;
    }
    // 보조 차원 ×1
    for (const { dim, sign } of r.secondary) {
      score += sign * (dimScores[dim] || 0) * 1;
    }

    // Q24 주민 가중치 반영
    score += residentWeights[key];

    residentScores[key] = score;
  }

  // 동점 처리: 1단계 전체 점수 → 2단계 주요 차원만 → 3단계 D5 점수
  const sorted = [...allKeys].sort((a, b) => {
    if (residentScores[a] !== residentScores[b]) {
      return residentScores[b] - residentScores[a];
    }

    // 2단계: 주요 차원만 재비교
    const aPrimary = RESIDENTS[a].primary.reduce(
      (sum, { dim, sign }) => sum + sign * (dimScores[dim] || 0) * 2,
      0,
    );
    const bPrimary = RESIDENTS[b].primary.reduce(
      (sum, { dim, sign }) => sum + sign * (dimScores[dim] || 0) * 2,
      0,
    );
    if (aPrimary !== bPrimary) {
      return bPrimary - aPrimary;
    }

    // 3단계: D5 점수로 최종 결정
    const d5Weight = (k: ResidentKey) => {
      const p = RESIDENTS[k].primary.find((d) => d.dim === 'D5');
      if (p) return p.sign * (dimScores.D5 || 0) * 2;
      const s = RESIDENTS[k].secondary.find((d) => d.dim === 'D5');
      if (s) return s.sign * (dimScores.D5 || 0) * 1;
      return 0;
    };
    return d5Weight(b) - d5Weight(a);
  });

  return sorted[0];
}

